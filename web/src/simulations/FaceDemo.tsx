import { useEffect, useState } from "react";
import { Smile, Eye, Sparkles, Circle } from "lucide-react";
import { bi } from "../data/project";
import { useLocale } from "../state/Locale";
import { useMedia } from "../state/useMedia";

/** Frames come directly from cuty.face.renderer.FaceRenderer, not a redesign. */
export default function FaceDemo() {
  const { t } = useLocale();
  const reduced = useMedia("(prefers-reduced-motion: reduce)");
  const [expression, setExpression] = useState("idle");
  const [gaze, setGaze] = useState(4);
  const [talk, setTalk] = useState(false);
  const [tick, setTick] = useState(0);
  useEffect(() => {
    if (reduced) return;
    const timer = window.setInterval(() => setTick((value) => value + 1), 140);
    return () => window.clearInterval(timer);
  }, [reduced]);
  const mouth = talk && !reduced ? [0, 1, 3, 2, 1, 0][tick % 6] : 0;
  const blinking = !reduced && tick % 29 === 28;
  const frame = (blinking ? 9 : gaze) * 4 + mouth;
  const expressions = [
    { id: "idle", text: bi("Neutral", "Neutral"), icon: Circle },
    { id: "listening", text: bi("Listening", "Escuchando"), icon: Eye },
    { id: "happy", text: bi("Happy", "Feliz"), icon: Smile },
    { id: "surprised", text: bi("Surprised", "Sorprendido"), icon: Sparkles },
  ];
  return (
    <div className="face-demo">
      <div className="eyebrow face-demo-label">
        {t(
          bi(
            "ORIGINAL ROBOT FACE / OFFLINE DEMO",
            "CARA ORIGINAL DEL ROBOT / DEMO LOCAL",
          ),
        )}
      </div>
      <div
        className={`face-screen robot-face ${expression} ${talk ? "talking" : ""}`}
        onPointerMove={(event) => {
          const bounds = event.currentTarget.getBoundingClientRect();
          const x = Math.max(
            0,
            Math.min(
              2,
              Math.floor(((event.clientX - bounds.left) / bounds.width) * 3),
            ),
          );
          const y = Math.max(
            0,
            Math.min(
              2,
              Math.floor(((event.clientY - bounds.top) / bounds.height) * 3),
            ),
          );
          setGaze(y * 3 + x);
        }}
        onPointerLeave={() => setGaze(4)}
      >
        <div className="face-original">
          <img
            src={`${import.meta.env.BASE_URL}face/${expression}.webp`}
            alt={t(
              bi(
                "Original C.U.T.Y face, rendered by the robot’s Python code",
                "Cara original de C.U.T.Y, renderizada por el código Python del robot",
              ),
            )}
            draggable={false}
            style={{
              transform: `translate(-${(frame % 5) * 20}%, -${Math.floor(frame / 5) * 12.5}%)`,
            }}
          />
        </div>
      </div>
      <div className="face-controls">
        {expressions.map((item) => (
          <button
            key={item.id}
            aria-pressed={expression === item.id}
            onClick={() => setExpression(item.id)}
          >
            <item.icon size={16} />
            {t(item.text)}
          </button>
        ))}
        <button
          aria-pressed={talk}
          disabled={reduced}
          onClick={() => setTalk((value) => !value)}
        >
          {t(
            talk
              ? bi("Stop mouth", "Detener boca")
              : bi("Animate mouth", "Animar boca"),
          )}
        </button>
      </div>
      <p className="caption">
        {t(
          bi(
            "These are frames generated by the same Python renderer used on the robot’s 480 × 320 display: original eyes, colors, cheeks and mouth. Move your pointer to guide the gaze. Mouth playback is a local simulation, not live audio or hardware control.",
            "Estos fotogramas los genera el mismo renderizador Python de la pantalla de 480 × 320 del robot: ojos, colores, mejillas y boca originales. Mueve el puntero para guiar la mirada. La boca es una simulación local, sin audio en vivo ni control del hardware.",
          ),
        )}
      </p>
    </div>
  );
}
